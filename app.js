// Custom Item Addition
function addCustomItem() {
  const val = customItemInput.value.trim();
  if (!val) {
    showToast('추가할 준비물 이름을 입력하세요!', '⚠️');
    customItemInput.focus();
    return;
  }

  state.checklistItems.push({
    id: Date.now(),
    category: '➕ 나만의 추가 준비물',
    name: val,
    tag: '직접추가',
    tagType: 'weather-tag',
    checked: false,
    isCustom: true
  });

  customItemInput.value = '';
  renderChecklist();
  showToast(`'${val}' 준비물이 추가되었습니다!`);
}

