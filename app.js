function renderCalendar() {
  const year = state.calYear;
  const month = state.calMonth; // 0-indexed

  calMonthTitle.textContent = `${year}년 ${month + 1}월`;

  const firstDayOfMonth = new Date(year, month, 1).getDay();
  const daysInMonth = new Date(year, month + 1, 0).getDate();

  calDaysGrid.innerHTML = '';

  // Leading empty blanks
  for (let i = 0; i < firstDayOfMonth; i++) {
    const empty = document.createElement('div');
    empty.className = 'cal-day-cell empty';
    calDaysGrid.appendChild(empty);
  }

  for (let day = 1; day <= daysInMonth; day++) {
    const cellDate = new Date(year, month, day);
    cellDate.setHours(0,0,0,0);

    const cell = document.createElement('div');
    cell.className = 'cal-day-cell';
    cell.innerHTML = `<span>${day}</span>`;

    // Past date check
    if (cellDate < today) {
      cell.classList.add('disabled');
    } else {
      // Range highlight check
      if (state.startDate && state.endDate) {
        const time = cellDate.getTime();
        const sTime = state.startDate.getTime();
        const eTime = state.endDate.getTime();

        if (time === sTime && time === eTime) {
          cell.classList.add('range-start', 'range-end');
          cell.innerHTML = `<span>${day}</span><span class="cal-tag">당일</span>`;
        } else if (time === sTime) {
          cell.classList.add('range-start');
          cell.innerHTML = `<span>${day}</span><span class="cal-tag">출발</span>`;
        } else if (time === eTime) {
          cell.classList.add('range-end');
          cell.innerHTML = `<span>${day}</span><span class="cal-tag">귀국</span>`;
        } else if (time > sTime && time < eTime) {
          cell.classList.add('in-range');
        }
      } else if (state.startDate) {
        if (cellDate.getTime() === state.startDate.getTime()) {
          cell.classList.add('range-start', 'range-end');
          cell.innerHTML = `<span>${day}</span><span class="cal-tag">출발</span>`;
        }
      }

      cell.addEventListener('click', () => onDateClicked(cellDate));
    }

    calDaysGrid.appendChild(cell);
  }
}

function onDateClicked(date) {
  if (!state.startDate || (state.startDate && state.endDate)) {
    // Start fresh selection
    state.startDate = date;
    state.endDate = null;
    state.isSelectingEnd = true;
    showToast('귀국일을 선택해 주세요 📅');
  } else if (state.startDate && !state.endDate) {
    if (date < state.startDate) {
      state.startDate = date;
      state.endDate = null;
      showToast('귀국일을 선택해 주세요 📅');
    } else {
      state.endDate = date;
      state.isSelectingEnd = false;
      const diffDays = Math.round((state.endDate - state.startDate) / (1000 * 60 * 60 * 24));
      showToast(`${diffDays}박 ${diffDays + 1}일 일정 선택 완료! 🎉`, '🛫');
    }
  }
  updateDateDisplay();
  renderCalendar();
}

function formatDate(d) {
  if (!d) return '선택 전';
  const days = ['일', '월', '화', '수', '목', '금', '토'];
  const m = d.getMonth() + 1;
  const day = d.getDate();
  const w = days[d.getDay()];
  return `${m}월 ${day}일 (${w})`;
}

function updateDateDisplay() {
  displayDeparture.textContent = formatDate(state.startDate);
  displayReturn.textContent = formatDate(state.endDate);

  if (state.startDate && state.endDate) {
    const diffDays = Math.round((state.endDate - state.startDate) / (1000 * 60 * 60 * 24));
    displayDuration.textContent = `${diffDays}박 ${diffDays + 1}일 (총 ${diffDays + 1}일)`;
  } else if (state.startDate) {
    displayDuration.textContent = '귀국일 선택 중...';
  } else {
    displayDuration.textContent = '일정 선택';
  }
}

